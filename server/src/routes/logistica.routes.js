const express = require("express");
const validarSolicitud = require("../middleware/validarSolicitud");
const subirImagen = require("../middleware/subirImagenProducto");
const c = require("../controllers/logistica.controller");
const s = require("../validators/logistica.schemas");
const router = express.Router();
router.get("/resumen",c.resumen);
router.get("/catalogos",c.catalogos);
router.post("/imagenes",subirImagen,c.subirImagen);
router.get("/productos/exportar",validarSolicitud({query:s.filtrosSchema}),c.exportar);
router.get("/productos",validarSolicitud({query:s.filtrosSchema}),c.listarProductos);
router.post("/productos",validarSolicitud({body:s.crearProductoSchema}),c.guardarProducto);
router.put("/productos/:id",validarSolicitud({params:s.idParamsSchema,body:s.actualizarProductoSchema}),c.guardarProducto);
router.get("/proveedores",validarSolicitud({query:s.filtrosSchema}),c.proveedores);
router.post("/proveedores",validarSolicitud({body:s.proveedorSchema}),c.guardarProveedor);
router.put("/proveedores/:id",validarSolicitud({params:s.idParamsSchema,body:s.proveedorSchema}),c.guardarProveedor);
router.patch("/proveedores/:id/estado",validarSolicitud({params:s.idParamsSchema,body:s.proveedorEstadoSchema}),c.estadoProveedor);
router.get("/movimientos",validarSolicitud({query:s.filtrosMovimientosSchema}),c.movimientos);
router.post("/movimientos",validarSolicitud({body:s.movimientoSchema}),c.registrarMovimiento);
router.get("/solicitudes-material",c.solicitudes);
router.patch("/solicitudes-material/:id/estado",validarSolicitud({params:s.idParamsSchema,body:s.solicitudEstadoSchema}),c.estadoSolicitud);
module.exports=router;
